    NEXT_PUBLIC_SUPABASE_ANON_KEY: anonJwt, SUPABASE_SERVICE_ROLE_KEY: serviceJwt, FAOLLA_CHECKOUT_RUNTIME_JWT: runtimeJwt,
    FAOLLA_BACKGROUND_JOBS_PAUSED: '1', MERCHANT_BOOKING_AUTOMATION_WORKER_ENABLED: 'false', MERCHANT_BOOKING_STORAGE_MODE: 'atomic-v2',
    MERCHANT_MEMBER_CHECKOUT_PILOT_SITES: site, MERCHANT_MEMBER_CHECKOUT_CART_PILOT_SITES: site, MERCHANT_MEMBER_CHECKOUT_CART_UI_PILOT_SITES: site,
