        if (req.method === 'PUT') {
          const chunks = []; let size = 0; for await (const chunk of req) { size += chunk.length; assert.ok(size <= 32768); chunks.push(chunk); }
          const patch = JSON.parse(Buffer.concat(chunks)); assert.deepEqual(Object.keys(patch).sort(), ['app_metadata', 'user_metadata']);
          users.set(user.id, { ...user, ...patch });
        }
        json(res, 200, users.get(user.id)); return;
