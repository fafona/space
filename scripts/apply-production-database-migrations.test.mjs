const VERSION_NAMES = new Map([
  [VERSIONS[0], "core_transaction_foundation"],
  [VERSIONS[1], "order_shadow_write_rpc"],
  [VERSIONS[2], "merchant_enterprise_foundation"],
]);

function migrationSource(version, name) {
  return `begin;
create table if not exists public.fixture_${version} (
  id bigint generated by default as identity primary key
);
insert into public.faolla_schema_migrations (version, name)
values (${version}, '${name}')
on conflict (version) do nothing;
commit;
`;
}

async function createFixture(t, definitions = null) {
  const root = await mkdtemp(
    path.join(os.tmpdir(), "faolla-production-migration-test-"),
  );
  t.after(() => rm(root, { recursive: true, force: true }));
  const directory = path.join(root, "scripts", "supabase-migrations");
  await mkdir(directory, { recursive: true });

  const items =
    definitions ??
    [
      [VERSIONS[2], "merchant_enterprise_foundation"],
      [VERSIONS[0], "core_transaction_foundation"],
      [VERSIONS[1], "order_shadow_write_rpc"],
    ];
  const sources = new Map();
  for (const [version, name] of items) {
    const fileName = `${version}_${name}.sql`;
    const source = migrationSource(version, name);
    await writeFile(path.join(directory, fileName), source, "utf8");
    sources.set(version, source);
  }
  return { root, directory, sources };
}

function selfHostedTopology(name = "supabase-db") {
  return {
    available: true,
    containerCount: 1,
    databaseCandidates: [
      {
        name,
        image: "supabase/postgres:15",
        probeSucceeded: true,
        tools: {
          psql: true,
          databaseConfigured: true,
          userConfigured: true,
        },
        mounts: [],
      },
    ],
    storageCandidates: [],
    error: null,
  };
}

function createRegistryCommandRunner(input = {}) {
  const applied = new Set(input.applied ?? []);
  const registeredNames = new Map(
    [...applied].map((version) => [
      version,
      VERSION_NAMES.get(version) ?? "unknown_migration",
    ]),
  );
  for (const [version, name] of Object.entries(
    input.registeredNames ?? {},
  )) {
    registeredNames.set(version, name);
  }
  let registryExists = input.registryExists ?? applied.size > 0;
  const calls = [];
  const runner = async (command, args, options = {}) => {
    calls.push({ command, args, options });
    assert.equal(command, "docker");
    assert.deepEqual(args.slice(0, 3), ["exec", "-i", "supabase-db"]);
    assert.equal(typeof options.input, "string");

    if (options.input.includes("__FAOLLA_REGISTRY__")) {
      const versions = [...applied].sort();
      return {
        status: 0,
        stdout: [
          `__FAOLLA_REGISTRY__ ${registryExists ? "true" : "false"}`,
          ...versions.map((version) =>
            JSON.stringify({
              version,
              name: registeredNames.get(version),
            }),
          ),
          "",
        ].join("\n"),
        stderr: "",
        timedOut: false,
      };
    }

    const registration = options.input.match(
      /values\s*\(\s*(\d{12})\s*,\s*'([a-z0-9_]+)'/i,
    );
    const version = registration?.[1];
    assert.match(version ?? "", /^\d{12}$/);
    if (version === input.failVersion) {
      return {
        status: 1,
        stdout: "",
        stderr: input.failureStderr ?? "simulated psql failure",
        stderrTruncated: input.failureStderrTruncated ?? false,
        timedOut: false,
      };
    }
    applied.add(version);
    registeredNames.set(version, registration[2]);
    registryExists = true;
    return {
      status: 0,
      stdout: "",
      stderr: "",
      timedOut: false,
    };
  };
  return { applied, calls, runner };
}

async function exists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

function assertMigrationError(error, code) {
  assert.equal(error instanceof ProductionDatabaseMigrationError, true);
  assert.equal(error.code, code);
  return true;
}

test("CLI arguments default to a read-only dry run and require explicit --apply", () => {
  assert.deepEqual(parseProductionMigrationArguments([]), {
    apply: false,
    dryRun: true,
    explicitDryRun: false,
    json: false,
    through: null,
  });
  assert.deepEqual(
    parseProductionMigrationArguments([
      "--apply",
      "--through=202607310001",
      "--json",
    ]),
    {
      apply: true,
      dryRun: false,
      explicitDryRun: false,
      json: true,
      through: "202607310001",
    },
  );
  assert.deepEqual(
    parseProductionMigrationArguments([
      "--dry-run",
      "--through",
      "202607250002",
    ]),
    {
      apply: false,
      dryRun: true,
      explicitDryRun: true,
      json: false,
      through: "202607250002",
    },
  );
  assert.throws(
    () => parseProductionMigrationArguments(["--apply", "--dry-run"]),
    (error) =>
      assertMigrationError(error, "migration_apply_and_dry_run_conflict"),
  );
  assert.throws(
    () => parseProductionMigrationArguments(["--through=not-a-version"]),
    (error) => assertMigrationError(error, "migration_through_invalid"),
  );
  assert.throws(
    () => parseProductionMigrationArguments(["--unexpected"]),
    (error) => assertMigrationError(error, "migration_argument_unknown"),
  );
});

