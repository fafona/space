test("default execution is dry-run, treats a missing registry as empty, and never sends a migration", async (t) => {
  const fixture = await createFixture(t);
  const lockPath = path.join(fixture.root, "migration.lock");
  const secret = "container-password-must-never-leak";
  const commands = createRegistryCommandRunner({
    registryExists: false,
  });

  const report = await applyProductionDatabaseMigrations({
    rootDir: fixture.root,
    through: VERSIONS[2],
    env: {
      POSTGRES_PASSWORD: secret,
    },
    selfHostedTopology: selfHostedTopology(),
    runCommand: commands.runner,
    lockPath,
  });

  assert.equal(report.status, "dry_run");
  assert.equal(report.mode, "dry_run");
  assert.equal(report.registryExists, false);
  assert.deepEqual(
    report.pending.map((migration) => migration.version),
    VERSIONS,
  );
  assert.deepEqual(report.executed, []);
  assert.equal(commands.calls.length, 1);
  assert.match(commands.calls[0].options.input, /json_build_object/);
  assert.match(commands.calls[0].options.input, /'name', name/);
  assert.equal(await exists(lockPath), false);

  const serializedCommands = JSON.stringify(commands.calls);
  assert.equal(serializedCommands.includes(secret), false);
  const shellScript = commands.calls[0].args.at(-1);
  assert.match(shellScript, /POSTGRES_PASSWORD/);
  assert.match(shellScript, /PGPASSWORD/);
  assert.match(shellScript, /supabase_admin/);
  assert.match(shellScript, /POSTGRES_DB/);
  assert.match(shellScript, /ON_ERROR_STOP=1/);
  assert.match(
    shellScript,
    /PGOPTIONS='-c lock_timeout=5s -c statement_timeout=900s'/,
  );
  assert.equal(JSON.stringify(report).includes(secret), false);
});

test("apply mode executes only unregistered migrations in filename order through stdin", async (t) => {
  const fixture = await createFixture(t);
  const commands = createRegistryCommandRunner({
    applied: [VERSIONS[0]],
    registryExists: true,
  });

  const report = await applyProductionDatabaseMigrations({
    apply: true,
    rootDir: fixture.root,
    through: VERSIONS[2],
    selfHostedTopology: selfHostedTopology(),
    runCommand: commands.runner,
    lockPath: path.join(fixture.root, "migration.lock"),
  });

  assert.equal(report.status, "applied");
  assert.deepEqual(
    report.pending.map((migration) => migration.version),
    VERSIONS.slice(1),
  );
  assert.deepEqual(
    report.executed.map((migration) => migration.version),
    VERSIONS.slice(1),
  );
  assert.deepEqual([...commands.applied].sort(), VERSIONS);

  const migrationCalls = commands.calls.filter(
    (call) => !call.options.input.includes("__FAOLLA_REGISTRY__"),
  );
  assert.deepEqual(
    migrationCalls.map(
      (call) =>
        call.options.input.match(/values\s*\(\s*(\d{12})\s*,/i)?.[1],
    ),
    VERSIONS.slice(1),
  );
  for (const [index, call] of migrationCalls.entries()) {
    const source = fixture.sources.get(VERSIONS[index + 1]);
    const lockIndex = call.options.input.indexOf(
      "SELECT pg_advisory_lock(20260731, 1);",
    );
    const sourceIndex = call.options.input.indexOf(source.trimEnd());
    const unlockIndex = call.options.input.indexOf(
      "SELECT pg_advisory_unlock(20260731, 1);",
    );
    assert.equal(lockIndex >= 0, true);
    assert.equal(sourceIndex > lockIndex, true);
    assert.equal(unlockIndex > sourceIndex, true);
  }
  assert.equal(
    migrationCalls.every(
      (call) =>
        !call.args.some((argument) =>
          argument.includes(call.options.input.slice(0, 20)),
        ),
    ),
    true,
  );
});

