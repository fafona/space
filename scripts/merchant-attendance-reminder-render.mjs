//Mechanical SOURCE renderer. --patch emits an apply_patch input; never writes.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {reminderRenderSections} from './merchant-attendance-reminder-installation.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const relative='scripts/supabase-migrations/202610080201_merchant_attendance_reminders.sql';
const before=readFileSync(path.join(root,relative),'utf8').replaceAll('\r\n','\n');
const sections=reminderRenderSections(root,before);let after=before;
for(const [key,body] of Object.entries(sections)){
 const name=key.toUpperCase(),pattern=new RegExp(`(-- BEGIN REMINDER ${name}\\n)[\\s\\S]*?(-- END REMINDER ${name})`);
 assert(pattern.test(after));after=after.replace(pattern,(_m,open,close)=>open+body+'\n'+close);
}
if(process.argv.includes('--patch')){
 if(before===after){process.stdout.write('');process.exit(0);}
 //One entire-file hunk remains deterministic and preserves all non-generated bytes.
 process.stdout.write('*** Begin Patch\n*** Update File: '+path.join(root,relative)+'\n@@\n'+before.trimEnd().split('\n').map(x=>'-'+x).join('\n')+'\n'+after.trimEnd().split('\n').map(x=>'+'+x).join('\n')+'\n*** End Patch\n');
}else{assert.equal(before,after,'201 generated sections drifted');process.stdout.write('201 generated sections match\n');}
