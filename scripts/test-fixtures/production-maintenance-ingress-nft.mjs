// Entirely in-memory host bridge, intentionally independent of the legacy
// test file. It does not start a process, touch a file or certify nft syntax.
export const INPUT = { appPort: 3000, publicSupabaseUrl: "https://db.example.test/", operationId: "11111111-2222-4333-8444-555555555555" };
export const TOKEN = "a".repeat(64);
const sha = (value) => createHash("sha256").update(value).digest("hex");
const FAMILIES = { kong: "kong", db: "supabase/postgres", rest: "postgrest/postgrest", auth: "supabase/gotrue",
  realtime: "supabase/realtime", storage: "supabase/storage-api", meta: "supabase/postgres-meta", studio: "supabase/studio",
  functions: "supabase/edge-runtime", analytics: "supabase/logflare", vector: "timberio/vector", imgproxy: "darthsim/imgproxy", supavisor: "supabase/supavisor" };
const save = (tool) => `# Generated by ${tool} v1.8.4 on Mon Sep 1 00:00:00 2026\n*filter\n:INPUT ACCEPT [0:0]\n:FORWARD ACCEPT [0:0]\n:OUTPUT ACCEPT [0:0]\n${tool === "ebtables-save" ? "" : "COMMIT\n"}# Completed on Mon Sep 1 00:00:00 2026\n`;
const match = (left, right, op = "==") => ({ match: { op, left, right } });
const meta = (key) => ({ meta: { key } });
const payload = (protocol, field) => ({ payload: { protocol, field } });
function ownedRows(plan) {
  let handle = 500;
  const rows = [{ table: { family: "inet", name: plan.tableName, handle: handle++ } }];
  const address = (role) => plan.containers.find((row) => row.service === role).address;
  const rule = (chain, expr) => rows.push({ rule: { family: "inet", table: plan.tableName, chain, handle: handle++, expr } });
  for (const name of ["input", "forward"]) rows.push({ chain: { family: "inet", table: plan.tableName, name, type: "filter", hook: name, prio: 200, policy: "accept", handle: handle++ } });
  for (const n of plan.inputPorts) rule("input", [match(meta("iifname"), "lo", "!="), match(meta("l4proto"), "tcp"), match(payload("tcp", "dport"), n), { drop: null }]);
  for (const [from, to] of [["kong", "rest"], ["kong", "auth"], ["rest", "db"], ["auth", "db"]]) {
    const interfaces = [match(meta("iifname"), plan.bridge), match(meta("oifname"), plan.bridge)];
    rule("forward", [...interfaces, match(payload("ip", "saddr"), address(from)), match(payload("ip", "daddr"), address(to)), { accept: null }]);
    rule("forward", [...interfaces, match(payload("ip", "saddr"), address(to)), match(payload("ip", "daddr"), address(from)),
      match({ ct: { key: "state" } }, "established", "in"), match({ ct: { key: "direction" } }, "reply"), { accept: null }]);
  }
  for (const row of plan.containers) rule("forward", [match(payload("ip", "daddr"), row.address), { drop: null }]);
  return rows;
}

export function createNftIngressHost(profile = "standard") {
  assert(["standard", "bt"].includes(profile));
  const bt = profile === "bt", prefix = bt ? "/www/server/nginx/conf" : "/etc/nginx";
  const ROOT = `${prefix}/nginx.conf`, SITE = bt ? "/www/server/panel/vhost/nginx/faolla.conf" : "/etc/nginx/sites-enabled/faolla.conf";
  const BINARY = bt ? "/www/server/nginx/sbin/nginx" : "/usr/sbin/nginx";
  const files = new Map([
    [ROOT, `# preserved root\nevents {}\nhttp { include ${SITE.slice(0, SITE.lastIndexOf("/"))}/*.conf; }\n`],
    [SITE, "# preserved sites\nserver { listen 443 ssl; server_name faolla.example.test; location / { proxy_pass http://127.0.0.1:3000; } }\n" +
      "server { listen 443 ssl; server_name db.example.test; location / { proxy_pass http://127.0.0.1:8000; } }\n" +
      "server { listen 888; server_name static.example.test; root /var/www/static; }\n"],
  ]);
  const networkId = "d".repeat(64), bridge = "br-" + networkId.slice(0, 12);
  const rows = Object.entries(FAMILIES).map(([service, family], index) => ({ id: (index + 1).toString(16).padStart(64, "0"),
    name: "/supabase-" + service, image: family + ":test", state: "running", project: "synthetic_supabase", service, mode: "synthetic_network",
    networks: { synthetic_network: { IPAddress: `172.20.0.${index + 2}`, NetworkID: networkId, GlobalIPv6Address: "" } },
    ports: service === "kong" ? { "8000/tcp": [{ HostIp: "0.0.0.0", HostPort: "8000" }], "8443/tcp": [{ HostIp: "::", HostPort: "8443" }] } :
      service === "supavisor" ? { "5432/tcp": [{ HostIp: "0.0.0.0", HostPort: "5432" }], "6543/tcp": [{ HostIp: "::", HostPort: "6543" }] } : {},
  }));
  const plan = planNftFirewall({ input: INPUT, docker: { bridge, containers: rows.map(row => ({ service: row.service,
    address: row.networks.synthetic_network.IPAddress, publishedPorts: Object.values(row.ports).flatMap(values => values.map(item => Number(item.HostPort))) })) } });
  const state = { files, private: new Map(), rows, mutations: [], calls: [], requests: [], worker: 101,
    nft: { nftables: [
      { metainfo: { version: "0.9.3", release_name: "Topsy", json_schema_version: 1 } },
      { table: { family: "inet", name: "firewalld", handle: 1 } },
      { chain: { family: "inet", table: "firewalld", name: "filter_INPUT", type: "filter", hook: "input", prio: 10, policy: "accept", handle: 1 } },
      { rule: { family: "inet", table: "firewalld", chain: "filter_INPUT", handle: 2, expr: [{ counter: { packets: 0, bytes: 0 } }, { xt: null }, { accept: null }] } },
    ] },
    saves: Object.fromEntries(["iptables-save", "ip6tables-save", "ebtables-save"].map(tool => [tool, save(tool)])) };
  const out = (stdout = "", stderr = "") => ({ stdout, stderr });
  const mutate = (kind, data, action) => { state.mutations.push({ kind, data }); action?.(); };
  const fact = (path) => ({ requestedPath: path, actualPath: path, content: files.get(path), mode: 0o644, uid: 0, gid: 0,
    link: null, parents: [`${prefix}:1:2`, "/:1:1"] });
  const d = {
    captureNetwork: () => ({ version: 1, links: [{ index: 1, name: "lo", qdisc: "noqueue", master: null, kind: null }],
      qdiscs: [{ index: 1, kind: "noqueue", handle: 0, parent: 4294967295 }] }),
    readFile: (path) => { assert(files.has(path)); return fact(path); },
    readText: (path) => path.startsWith("/proc/sys/net/bridge/") ? "1" : /^\/proc\/[0-9]+\/stat$/.test(path)
      ? `${path.split("/")[2]} (nginx) ${Array.from({ length: 20 }, (_, i) => i === 19 ? path.split("/")[2] + "45" : "0").join(" ")}` : assert.fail("unexpected read"),
    readPrivate: (path) => state.private.get(path) ?? null,
    listIncludes: (pattern) => {
      const match = new RegExp("^" + pattern.split("*").map(part => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("[^/]*") + "$");
      return [...files.keys()].filter(path => match.test(path)).sort();
    },
    createPrivate: (path, content) => mutate("create-private", path, () => { assert(!state.private.has(path)); state.private.set(path, content); }),
    writeExact: (file, expected, next) => mutate("write", file.requestedPath, () => { assert.equal(sha(files.get(file.requestedPath)), expected); files.set(file.requestedPath, next); }),
    probeHeaders: { apikey: "synthetic-" + "b".repeat(32), authorization: "Bearer synthetic-" + "b".repeat(32) },
    async fetch(url, options) {
      state.requests.push({ url, options }); assert.equal(options.method, "GET"); assert.equal(options.cache, "no-store");
      const path = new URL(url).pathname, allowed = options.headers["x-faolla-maintenance-control"] === TOKEN;
      if (allowed && path === "/rest/v1/") return Response.json({ swagger: "2.0", paths: {} });
      if (allowed && path === "/auth/v1/settings") return Response.json({ external: {}, disable_signup: true });
      return new Response("maintenance", { status: 503 });
    },
    run(command, args, options) {
      state.calls.push({ command, args, options });
      if (command === BINARY) {
        if (args[0] === "-V") return out("", `nginx version: nginx/1.26.0\nconfigure arguments: --with-http_realip_module ${bt ? "--prefix=/www/server/nginx" : "--conf-path=/etc/nginx/nginx.conf"}`);
        if (args[0] === "-T") return out([...files, ...(files.get(ROOT).includes("faolla-maintenance-") ? [...state.private] : [])].map(([path, content]) => `# configuration file ${path}:\n${content}\n`).join(""));
        assert(args[0] === "-t" || args[0] === "-s");
        mutate(args[0] === "-t" ? "syntax" : "reload", command + " " + args.join(" "), () => { if (args[0] === "-s") state.worker++; });
        return out("", "nginx: configuration file test is successful");
      }
      if (command === "ps") return out(`100 1 0 nginx: master process ${BINARY}\n${state.worker} 100 33 nginx: worker process\n`);
      if (command === "readlink") return out(args[0].endsWith("/ns/net") ? "net:[1234]\n" : BINARY + "\n");
      if (command === "ip") return out(JSON.stringify([{ ifname: bridge, linkinfo: { info_kind: "bridge" } }]));
      if (command === "docker") {
        assert.deepEqual(args.slice(0, 2), ["--host", "unix:///var/run/docker.sock"]);
        if (args[2] === "ps") return out(rows.map(row => JSON.stringify(row.id)).join("\n"));
        if (args[2] === "inspect") return out(rows.map(row => JSON.stringify(row)).join("\n"));
        if (args[2] === "network") return out(JSON.stringify({ Id: networkId, Driver: "bridge", Scope: "local", EnableIPv6: false, Containers: Object.fromEntries(rows.map(row => [row.id, {}])) }));
      }
      if (["nft", "iptables", "ip6tables", "iptables-save", "ip6tables-save", "ebtables-save"].includes(command) && args[0] === "--version")
        return out(command === "nft" ? "nftables v0.9.3 (Topsy)" : `${command} v1.8.4 (nf_tables)`);
      if (Object.hasOwn(state.saves, command)) { assert.deepEqual(args, command === "ebtables-save" ? [] : ["-c"]); return out(state.saves[command]); }
      if (command === "nft" && args[0] === "-j") { assert.deepEqual(args, ["-j", "-a", "-n", "list", "ruleset"]); return out(JSON.stringify(state.nft)); }
      if (command === "nft") {
        assert.deepEqual(args, ["-f", "-"]); assert.deepEqual(Object.keys(options), ["input"]);
        mutate("nft", options.input, () => {
          if (options.input === plan.script) state.nft.nftables.push(...ownedRows(plan));
          else { assert.equal(options.input, `delete table inet ${plan.tableName}\n`); state.nft.nftables = state.nft.nftables.filter(row => (row.table?.name ?? row.chain?.table ?? row.rule?.table) !== plan.tableName); }
        });
        return out();
      }
      assert.fail("unexpected command (including any legacy firewall write)");
    },
  };
  return { state, d, plan, ROOT, SITE, BINARY, prefix, capture: () => captureIngress(INPUT, d), ownedRows: () => ownedRows(plan) };
}
